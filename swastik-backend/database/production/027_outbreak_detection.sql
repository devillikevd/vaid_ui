-- ═══════════════════════════════════════════════════════════════════
-- 027: Disease Outbreak Detection Tables
-- ═══════════════════════════════════════════════════════════════════
-- Two new tables for the area-wise disease outbreak prediction system.
-- health_events  → collects anonymized health signals from all sources
-- outbreak_alerts → stores detected anomalies with severity and location
-- ═══════════════════════════════════════════════════════════════════

-- ─── Table 1: health_events ───
-- Stores anonymized health signals from all data sources.
-- Each row represents ONE health event (appointment, prescription,
-- emergency request, or chatbot interaction) with only area-level
-- location and age group — no personally identifiable information.

CREATE TABLE IF NOT EXISTS health_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Source of the health signal
  source TEXT NOT NULL,                -- 'appointment' | 'prescription' | 'emergency' | 'chatbot' | 'diagnostic'
  source_id UUID,                      -- FK to the originating record (optional)

  -- Health signal data
  event_type TEXT NOT NULL,            -- Normalized disease/symptom cluster (e.g. 'dengue', 'respiratory')
  symptoms TEXT[] DEFAULT '{}',        -- Array of detected symptom keywords
  diagnosis TEXT,                      -- Raw diagnosis text (if from prescription)
  severity TEXT DEFAULT 'low',         -- 'low' | 'medium' | 'high' | 'critical'

  -- Anonymized location (area-level only)
  city TEXT,
  state TEXT,
  pincode TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,

  -- Anonymized demographics (no PII)
  patient_age_group TEXT,              -- '0-4' | '5-17' | '18-34' | '35-49' | '50-64' | '65+'
  patient_gender TEXT,                 -- 'male' | 'female' | 'other' | 'unknown'

  -- Timestamps
  event_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Performance indexes for aggregation queries
CREATE INDEX IF NOT EXISTS idx_health_events_city_date ON health_events(city, event_date);
CREATE INDEX IF NOT EXISTS idx_health_events_pincode_date ON health_events(pincode, event_date);
CREATE INDEX IF NOT EXISTS idx_health_events_event_type ON health_events(event_type);


-- ─── Table 2: outbreak_alerts ───
-- Stores detected anomalies (outbreaks) generated by the analysis engine.
-- Each alert represents a statistically significant spike in a specific
-- disease/symptom in a specific geographic area.

CREATE TABLE IF NOT EXISTS outbreak_alerts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Alert classification
  alert_type TEXT NOT NULL,            -- 'anomaly_detection' | 'manual' | 'threshold'
  disease_or_symptom TEXT NOT NULL,    -- Normalized disease name (e.g. 'dengue', 'malaria')
  severity TEXT NOT NULL DEFAULT 'watch', -- 'watch' | 'warning' | 'critical'

  -- Location
  city TEXT,
  state TEXT,
  pincode TEXT,
  latitude DOUBLE PRECISION,          -- Centroid of affected area
  longitude DOUBLE PRECISION,

  -- Statistical data
  event_count INTEGER NOT NULL DEFAULT 0,   -- Cases in current analysis window
  baseline_count INTEGER NOT NULL DEFAULT 0, -- Expected cases based on 30-day baseline
  deviation_score DOUBLE PRECISION DEFAULT 0, -- Z-score (how many std devs above normal)
  affected_area_radius_km DOUBLE PRECISION DEFAULT 5,

  -- Demographics breakdown (anonymized)
  age_groups JSONB DEFAULT '{}',       -- e.g. {"18-34": 5, "35-49": 3}
  gender_distribution JSONB DEFAULT '{}', -- e.g. {"male": 4, "female": 4}

  -- Response
  recommendations TEXT,                -- Auto-generated health advisory text
  status TEXT DEFAULT 'active',        -- 'active' | 'monitoring' | 'resolved' | 'dismissed'

  -- Lifecycle
  detected_at TIMESTAMPTZ DEFAULT NOW(),
  resolved_at TIMESTAMPTZ,
  resolved_by UUID,                    -- Admin who resolved/dismissed
  admin_notes TEXT,

  -- Timestamps
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Performance indexes
CREATE INDEX IF NOT EXISTS idx_outbreak_alerts_status ON outbreak_alerts(status);
CREATE INDEX IF NOT EXISTS idx_outbreak_alerts_city ON outbreak_alerts(city);
CREATE INDEX IF NOT EXISTS idx_outbreak_alerts_severity ON outbreak_alerts(severity);
CREATE INDEX IF NOT EXISTS idx_outbreak_alerts_detected ON outbreak_alerts(detected_at);


-- ─── Row Level Security ───

ALTER TABLE health_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE outbreak_alerts ENABLE ROW LEVEL SECURITY;

-- Allow service role (backend) full access
DROP POLICY IF EXISTS "Allow service role full access on health_events" ON health_events;
CREATE POLICY "Allow service role full access on health_events"
  ON health_events FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow service role full access on outbreak_alerts" ON outbreak_alerts;
CREATE POLICY "Allow service role full access on outbreak_alerts"
  ON outbreak_alerts FOR ALL USING (true) WITH CHECK (true);

-- Drop old policies (from earlier manual run) if they exist
DROP POLICY IF EXISTS "Allow public read access for health_events" ON health_events;
DROP POLICY IF EXISTS "Allow public read access for outbreak_alerts" ON outbreak_alerts;
