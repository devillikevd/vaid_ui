function renderLine(line: string, index: number) {
  const trimmed = line.trim();
  if (!trimmed) return <div key={index} className="h-2" aria-hidden="true" />;

  // Article headings and document title.
  if (/^(Article\s+[IVXLC]+\.)/i.test(trimmed)) {
    return <h2 key={index} className="scroll-mt-28 pt-7 text-xl font-semibold tracking-tight text-slate-900 sm:text-2xl">{trimmed}</h2>;
  }
  if (/^(Privacy Policy|Privacy at a glance|Patients|Guardians and family members|Providers|Ambulance Operators and drivers|Healthcare Agents and Sahayaks|Website visitors|Device permissions and sensors)$/i.test(trimmed)) {
    return <h3 key={index} className="pt-5 text-base font-semibold text-slate-900 sm:text-lg">{trimmed}</h3>;
  }
  if (/^\d{1,2}\.\d{1,2}\s/.test(trimmed)) {
    return <p key={index} className="pt-2 text-[15px] leading-7 text-slate-700">{trimmed}</p>;
  }
  if (/^\d+\.\d+\s/.test(trimmed)) {
    return <p key={index} className="pt-2 text-[15px] leading-7 text-slate-700">{trimmed}</p>;
  }
  // Table headings and rows from PDF extraction are displayed in a readable pre-wrapped format.
  if (/\s{2,}/.test(line) && line.trim().length < 240) {
    return <p key={index} className="whitespace-pre-wrap font-sans text-sm leading-6 text-slate-700">{trimmed}</p>;
  }
  return <p key={index} className="text-[15px] leading-7 text-slate-700">{trimmed}</p>;
}

