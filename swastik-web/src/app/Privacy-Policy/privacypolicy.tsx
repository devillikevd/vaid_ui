function renderLine(line: string, index: number) {
  const trimmed = line.trim();
  if (!trimmed) return <div key={index} className="h-2" aria-hidden="true" />;

  if (trimmed === "__PRIVACY_AT_A_GLANCE_TABLE__") {
    return renderSummaryTable(privacyAtAGlanceRows, index);
  }

  if (trimmed === "__PRIVACY_POLICY_SUMMARY_TABLE__") {
    return renderSummaryTable(privacyPolicySummaryRows, index);
  }

  if (trimmed === "__PRIVACY_DEFINITIONS_TABLE__") {
    return renderDefinitionsTable(allPrivacyDefinitions, index);
  }

  if (trimmed === "__PRIVACY_DATA_ROLE_TABLE__") {
    return renderDataRoleTable(index);
  }

  if (trimmed === "__PRIVACY_PATIENT_DATA_TABLE__") {
    return renderPatientDataTable(index);
  }

  if (trimmed === "__PRIVACY_PERMISSIONS_TABLE__") {
    return renderPermissionsTable(index);
  }

  if (trimmed === "__PRIVACY_COLLECTION_METHODS__") {
    return renderCollectionMethods(index);
  }

  if (trimmed === "__PRIVACY_PURPOSES_TABLE__") {
    return renderPurposesTable(index);
  }

  if (trimmed === "__PRIVACY_SOS_RECIPIENTS_TABLE__") {
    return renderSosRecipientsTable(index);
  }

  if (trimmed === "__PRIVACY_DISCLOSURE_TABLE__") {
    return renderDisclosureTable(index);
  }

  if (trimmed === "__PRIVACY_SERVICE_PROVIDERS_TABLE__") {
    return renderServiceProvidersTable(index);
  }

  if (trimmed === "__PRIVACY_RETENTION_TABLE__") {
    return renderRetentionTable(index);
  }

  if (trimmed === "__PRIVACY_GRIEVANCE_CONTACT_TABLE__") {
    return renderGrievanceContactTable(index);
  }

  // Article headings and document title.
  if (/^(Article\s+[IVXLC]+\.)/i.test(trimmed)) {
    return <h2 key={index} className="scroll-mt-28 pt-7 text-xl font-semibold tracking-tight text-slate-900 sm:text-2xl">{trimmed}</h2>;
  }
  if (/^(Privacy Policy|Privacy at a glance|Patients|Guardians and family members|Providers|Ambulance Operators and drivers|Healthcare Agents and Sahayaks|Website visitors|Device permissions and sensors)$/i.test(trimmed)) {
    return <h3 key={index} className="pt-5 text-base font-semibold text-slate-900 sm:text-lg">{trimmed}</h3>;
  }
  const clauseMatch = trimmed.match(/^(\d+(?:\.\d+)?[A-Z]?)\s+(.*)$/);
  if (clauseMatch) {
    const [, clauseNumber, clauseText] = clauseMatch;
    return (
      <p key={index} className="my-4 grid grid-cols-[3.25rem_minmax(0,1fr)] gap-2 text-[15px] leading-7 text-slate-700">
        <span className="pt-0.5 text-sm font-semibold tabular-nums text-teal-700">{clauseNumber}</span>
        <span>{clauseText}</span>
      </p>
    );
  }
  // Table headings and rows from PDF extraction are displayed in a readable pre-wrapped format.
  if (/\s{2,}/.test(line) && line.trim().length < 240) {
    return <p key={index} className="whitespace-pre-wrap font-sans text-sm leading-6 text-slate-700">{trimmed}</p>;
  }
  return <p key={index} className="text-[15px] leading-7 text-slate-700">{trimmed}</p>;
}

function normalizePolicyLines(text: string) {
  const sourceLines = text.split("\n");
  const normalizedLines: string[] = [];

  for (let index = 0; index < sourceLines.length; index += 1) {
    const currentLine = sourceLines[index];
    const trimmed = currentLine.trim();

    if (!/^\d+(?:\.\d+)?[A-Z]?\s+/.test(trimmed)) {
      normalizedLines.push(currentLine);
      continue;
    }

    const clauseLines = [trimmed];
    while (index + 1 < sourceLines.length) {
      const nextLine = sourceLines[index + 1];
      const nextTrimmed = nextLine.trim();

      if (
        !nextTrimmed ||
        /^\d+(?:\.\d+)?[A-Z]?\s+/.test(nextTrimmed) ||
        /^Article\s+[IVXLC]+\./i.test(nextTrimmed) ||
        /^(Question Short answer|Term Meaning|__)/.test(nextTrimmed)
      ) {
        break;
      }

      clauseLines.push(nextTrimmed);
      index += 1;
    }

    normalizedLines.push(clauseLines.join(" "));
  }

  return normalizedLines;
}

